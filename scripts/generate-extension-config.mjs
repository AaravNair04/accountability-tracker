import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");

const configPath = path.join(rootDir, "extension.config.json");
const manifestPath = path.join(rootDir, "manifest.json");
const tsConfigPath = path.join(rootDir, "src", "extensionConfig.ts");

const rawConfig = JSON.parse(
  fs.readFileSync(configPath, "utf8")
);

const appBaseUrl =
  typeof rawConfig.appBaseUrl === "string"
    ? rawConfig.appBaseUrl.replace(/\/$/, "")
    : "";

if (!/^https:\/\/[^/]+/.test(appBaseUrl)) {
  throw new Error(
    "extension.config.json appBaseUrl must be an https URL."
  );
}

const manifest = {
  manifest_version: 3,
  name: "Accountability Tracker",
  version: "0.1.0",
  description: "Tracks active usage of selected websites.",
  permissions: [
    "tabs",
    "storage",
    "alarms"
  ],
  host_permissions: [
    `${appBaseUrl}/*`
  ],
  background: {
    service_worker: "dist/background.js",
    type: "module"
  },
  action: {
    default_title: "Accountability Tracker",
    default_popup: "src/popup/popup.html"
  },
  content_scripts: [
    {
      matches: [
        `${appBaseUrl}/devices/link*`
      ],
      js: [
        "dist/linkBridge.js"
      ],
      run_at: "document_start"
    }
  ]
};

fs.writeFileSync(
  manifestPath,
  `${JSON.stringify(manifest, null, 2)}\n`
);

fs.writeFileSync(
  tsConfigPath,
  [
    "// This file is generated by scripts/generate-extension-config.mjs.",
    "// Edit extension.config.json, then run npm run generate:extension-config.",
    `export const APP_BASE_URL = ${JSON.stringify(appBaseUrl)};`,
    ""
  ].join("\n")
);
